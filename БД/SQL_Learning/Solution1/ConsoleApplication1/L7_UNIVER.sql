SELECT p.PROFESSION_NAME                   AS [Специальность],
       s.SUBJECT_NAME                      AS [Дисциплина],
       AVG(CAST(pr.NOTE AS DECIMAL(5, 2))) AS [Средняя оценка]
FROM PROGRESS pr
         JOIN STUDENT st ON pr.IDSTUDENT = st.IDSTUDENT
         JOIN GROUPS g ON st.IDGROUP = g.IDGROUP
         JOIN PROFESSION p ON g.PROFESSION = p.PROFESSION
         JOIN SUBJECT s ON pr.SUBJECT = s.SUBJECT
WHERE g.FACULTY = N'ИТ'
GROUP BY ROLLUP (p.PROFESSION_NAME, s.SUBJECT_NAME);

