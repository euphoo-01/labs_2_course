SELECT f.FACULTY_NAME     AS [Факультет],
       g.IDGROUP          AS [Группа],
       COUNT(s.IDSTUDENT) AS [Кол-во студентов]
FROM STUDENT s
         JOIN GROUPS g ON s.IDGROUP = g.IDGROUP
         JOIN FACULTY f ON g.FACULTY = f.FACULTY
GROUP BY ROLLUP (f.FACULTY_NAME, g.IDGROUP);


