-- 1. INNER JOIN + LIKE
-- Вывод значений показателей и их названий, где в названии есть слово "Прибыль"
SELECT V.[Значение], T.[Название показателя]
FROM [Значения показателей] V
    INNER JOIN [Типы показателей] T ON V.[ID типа показателя] = T.[ID типа]
WHERE T.[Название показателя] LIKE N'%Прибыль%';


-- 2. Сложный JOIN + CASE + BETWEEN + ORDER BY
-- Вывод предприятия, названия показателя и текстовой оценки значения (НИЗКОЕ/СРЕДНЕЕ/ВЫСОКОЕ)
-- Аналог задачи про оценки студентов (шесть, семь, восемь)
SELECT P.[Название предприятия], 
       T.[Название показателя], 
       V.[Значение],
       CASE 
           WHEN V.[Значение] < 2000 THEN N'НИЗКОЕ'
           WHEN V.[Значение] BETWEEN 2000 AND 4000 THEN N'СРЕДНЕЕ'
           WHEN V.[Значение] > 4000 THEN N'ВЫСОКОЕ'
END AS [Уровень показателя]
FROM [Значения показателей] V
INNER JOIN [Предприятия] P ON V.[ID предприятия] = P.[ID предприятия]
INNER JOIN [Типы показателей] T ON V.[ID типа показателя] = T.[ID типа]
WHERE V.[Значение] BETWEEN 1000 AND 8000
ORDER BY V.[Значение] DESC;


-- 3. LEFT OUTER JOIN + ISNULL
-- Вывод всех предприятий. Если данных по показателям нет, выводится "***"
-- Аналог задачи про кафедры без преподавателей
SELECT P.[Название предприятия], 
       ISNULL(CAST(V.[Значение] AS NVARCHAR), N'***') AS [Значение]
FROM [Предприятия] P
    LEFT OUTER JOIN [Значения показателей] V ON P.[ID предприятия] = V.[ID предприятия];


-- 4. FULL OUTER JOIN (Вариант А)
-- Полное внешнее соединение предприятий и значений
SELECT P.[Название предприятия], V.[Значение]
FROM [Предприятия] P
    FULL OUTER JOIN [Значения показателей] V ON P.[ID предприятия] = V.[ID предприятия];


-- 5. FULL OUTER JOIN (Вариант Б - Доказательство коммутативности)
-- Тот же запрос, но таблицы поменяны местами. Результат по составу данных идентичен.
SELECT P.[Название предприятия], V.[Значение]
FROM [Значения показателей] V
    FULL OUTER JOIN [Предприятия] P ON V.[ID предприятия] = P.[ID предприятия];


-- 6. CROSS JOIN (с фильтрацией в WHERE)
-- Имитация INNER JOIN через перекрестное соединение
-- Аналог задачи про аудитории и их типы
SELECT V.[Значение], T.[Название показателя]
FROM [Значения показателей] V
    CROSS JOIN [Типы показателей] T
WHERE V.[ID типа показателя] = T.[ID типа];